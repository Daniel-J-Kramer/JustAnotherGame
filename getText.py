


def getText(name: str, strings: list):
    if name == "MAINTEXT":
        return strings[0]
    elif name == "QUESTIONTEXT":
        return strings[1]
    elif name == "STRINGONE":
        return strings[2]
    elif name == "STRINGTWO":
        return strings[3]
    elif name == "STRINGTHREE":
        return strings[4]
    elif name == "STRINGFOUR":
        return strings[5]
    return ""